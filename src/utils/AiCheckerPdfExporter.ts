/**
 * 3. Download Clean Edited Document PDF (WITHOUT Highlights or Badges)
 */
export async function downloadCleanPdfDocument(check: DocumentCheck): Promise<void> {
  const cleanBaseName = check.filename.replace(/\.[^/.]+$/, '');
  const pdfFileName = `Clean_Edited_${cleanBaseName}.pdf`;

  let contentHtml = `
    <div style="font-family: 'Times New Roman', Times, serif; color: #000000; line-height: 1.6; padding: 40px; max-width: 750px; margin: 0 auto;">
      <h1 style="font-size: 20px; font-weight: bold; text-align: center; margin-bottom: 24px;">${cleanBaseName}</h1>
      <div style="font-size: 12pt; text-align: justify; white-space: pre-wrap;">${check.edited.text}</div>
    </div>
  `;

  openPrintWindow(pdfFileName, contentHtml);
}

function openPrintWindow(fileName: string, contentHtml: string): void {
  const printWindow = window.open('', '_blank');
  if (printWindow) {
    printWindow.document.write(`
      <html>
        <head>
          <title>${fileName}</title>
          <style>
            @media print {
              body { margin: 0; padding: 0; }
              mark { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
            }
          </style>
        </head>
        <body>
          ${contentHtml}
          <script>
            window.onload = function() {
              window.print();
              setTimeout(function() { window.close(); }, 500);
            };
          </script>
        </body>
      </html>
    `);
    printWindow.document.close();
  }
}
